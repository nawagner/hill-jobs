"""Regenerate the member and committee tables from unitedstates/congress-legislators.

Writes app/data/member_data.py (every current senator and representative, with
chamber, party, state and committee assignments) and app/data/member_committees.py
(committee and subcommittee names). Rerun it when members change, e.g. after a
special election or the start of a new Congress:

    cd apps/api && uv run --with pyyaml python scripts/generate_member_data.py

Pass --from-dir DIR to read the three YAML files from disk instead of downloading.
"""

import argparse
import pathlib
import sys

import httpx
import yaml

BASE_URL = "https://unitedstates.github.io/congress-legislators/"
FILES = (
    "legislators-current.yaml",
    "committees-current.yaml",
    "committee-membership-current.yaml",
)
PARTY_CODES = {"Democrat": "D", "Republican": "R", "Independent": "I"}
DATA_DIR = pathlib.Path(__file__).resolve().parent.parent / "app" / "data"


def load(name: str, from_dir: pathlib.Path | None):
    if from_dir:
        text = (from_dir / name).read_text()
    else:
        resp = httpx.get(BASE_URL + name, timeout=60, follow_redirects=True)
        resp.raise_for_status()
        text = resp.text
    return yaml.safe_load(text)


def build_committees(committees: list[dict]) -> dict[str, dict]:
    result: dict[str, dict] = {}
    for c in committees:
        cid = c["thomas_id"]
        result[cid] = {"name": c["name"], "chamber": c["type"], "parent": None}
        for sub in c.get("subcommittees", []):
            result[cid + sub["thomas_id"]] = {
                "name": sub["name"],
                "chamber": c["type"],
                "parent": cid,
            }
    return result


def build_members(legislators: list[dict], membership: dict[str, list[dict]]) -> list[dict]:
    committees_by_member: dict[str, list[str]] = {}
    for cid, roster in membership.items():
        for m in roster:
            committees_by_member.setdefault(m["bioguide"], []).append(cid)

    members = []
    for leg in legislators:
        term = leg["terms"][-1]
        name = leg["name"]
        bioguide = leg["id"]["bioguide"]
        members.append({
            "id": bioguide,
            "chamber": "senate" if term["type"] == "sen" else "house",
            "official_full": name.get("official_full") or f"{name['first']} {name['last']}",
            "first": name["first"],
            "middle": name.get("middle"),
            "nickname": name.get("nickname"),
            "last": name["last"],
            "party": PARTY_CODES[term["party"]],
            "state": term["state"],
            "committees": sorted(committees_by_member.get(bioguide, [])),
        })
    members.sort(key=lambda m: (m["chamber"] != "senate", m["last"], m["first"]))
    return members


def write_members(members: list[dict]) -> None:
    lines = [
        "# Generated by scripts/generate_member_data.py from unitedstates/congress-legislators.",
        "# Do not edit by hand; rerun the script instead.",
        "",
        "MEMBERS: list[dict] = [",
    ]
    for m in members:
        lines.append(f"    {m!r},")
    lines.append("]")
    (DATA_DIR / "member_data.py").write_text("\n".join(lines) + "\n")


def write_committees(committees: dict[str, dict]) -> None:
    lines = [
        "# Committee and subcommittee names, keyed by Congress.gov (THOMAS) code.",
        "# Generated by scripts/generate_member_data.py from unitedstates/congress-legislators.",
        "# Do not edit by hand; rerun the script instead.",
        "",
        "COMMITTEES: dict[str, dict] = {",
    ]
    order = sorted(committees, key=lambda k: (committees[k]["parent"] is not None, k))
    for cid in order:
        lines.append(f"    {cid!r}: {committees[cid]!r},")
    lines.append("}")
    (DATA_DIR / "member_committees.py").write_text("\n".join(lines) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--from-dir", type=pathlib.Path)
    args = parser.parse_args()

    legislators, committees, membership = (load(f, args.from_dir) for f in FILES)
    members = build_members(legislators, membership)
    write_members(members)
    write_committees(build_committees(committees))
    print(f"Wrote {len(members)} members and committees to {DATA_DIR}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
